# Launchers inflate widgets with system fonts only: an app's own @font is ignored. Styles that need
# a bundled face (Doto, Literata) therefore get an ImageView "twin" after each text view; the
# factory draws the text in the real font into it (WidgetBitmapText) and the TextView stays gone
# (kept so every style shares the same ids and code path).
BITMAP_TEXT = {"dot", "almanac"}
TWIN_IDS = ["widget_item_category", "widget_item_index", "widget_item_hook", "widget_item_title"]
KEEP = ("android:layout_width", "android:layout_height", "android:layout_weight", "android:layout_margin",
        "android:background", "android:padding")

def add_twins(xml):
    import re
    for vid in TWIN_IDS:
        m = re.search(r'( *)<TextView\n(\s*)android:id="@\+id/%s"(.*?)/>' % vid, xml, re.S)
        if not m:
            continue
        indent, block = m.group(1), m.group(0)
        attrs = re.findall(r'(android:[a-zA-Z_]+)="([^"]*)"', block)
        keep = [(k, v) for k, v in attrs if k.startswith(KEEP)]
        lines = [f'{indent}    android:id="@+id/{vid}_img"'] + [f'{indent}    {k}="{v}"' for k, v in keep]
        # The fact fills a fixed area (weight 1) and may scale down to fit it. Labels draw 1:1
        # ("matrix"): fitStart + adjustViewBounds stretched a short title to the row's width.
        if vid == "widget_item_hook":
            lines.append(f'{indent}    android:scaleType="fitStart"')
        else:
            lines.append(f'{indent}    android:scaleType="matrix"')
        # Text is set at runtime (setContentDescription); the card number is decorative.
        if vid == "widget_item_index":
            lines.append(f'{indent}    android:importantForAccessibility="no"')
        lines.append(f'{indent}    android:contentDescription="@null"')
        twin = f"\n{indent}<ImageView\n" + "\n".join(lines) + " />"
        gone = block.replace(f'android:id="@+id/{vid}"', f'android:id="@+id/{vid}"\n{indent}    android:visibility="gone"', 1)
        xml = xml.replace(block, gone + "\n" + twin, 1)
    return xml

for k, s in STYLES.items():
    xml = layout(k, s)
    if k in BITMAP_TEXT:
        xml = add_twins(xml)
    open(os.path.join(OUT, f"widget_wiki_item_{k}.xml"), "w").write(xml)
